package operators;

public class relational {
    public static void main(String args[]){
        int a=12;
        int b=25;
        int c=25;
        System.out.println(a==b);
        System.out.println(b==c);
        System.out.println(a>b);
        System.out.println(b>c);
        System.out.println(a!=b);
        System.out.println(b!=c);
        System.out.println(a<=b);
    }
}
