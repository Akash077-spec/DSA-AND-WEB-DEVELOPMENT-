public class variable {
    public static void main (String args[]){
        int a= 10;
        int b=20;
        System.out.println(a);
        System.out.println(b);
        // we can change the variable values 
      
         a =66;
         System.out.println(a);
         // we can assign variable to another variable
         a=b;
         System.out.println(a);
    }
}
